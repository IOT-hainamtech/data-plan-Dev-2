-- Dev-only bootstrap; runs once on an EMPTY PostgreSQL data volume.
-- For the M1 demo all TIMESTAMP WITHOUT TIME ZONE values represent UTC.
-- Device/Rule seeds are placeholders until nextGRP config sync exists.
CREATE EXTENSION IF NOT EXISTS timescaledb;

CREATE TABLE IF NOT EXISTS devices (
    device_id VARCHAR(64) PRIMARY KEY,
    org_code VARCHAR(64) NOT NULL,
    site_code VARCHAR(64) NOT NULL,
    profile_code VARCHAR(64) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);
INSERT INTO devices (device_id, org_code, site_code, profile_code, enabled)
VALUES ('TH-001', 'demo', 'demo-site', 'TEMP_HUM_SENSOR', TRUE),
       ('DR-001', 'demo', 'demo-site', 'DOOR_SENSOR', TRUE)
ON CONFLICT (device_id) DO NOTHING;

-- Unique constraints on hypertables MUST include the partition time column.
CREATE TABLE IF NOT EXISTS telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    device_id VARCHAR(64) NOT NULL REFERENCES devices(device_id),
    boot_id VARCHAR(64) NOT NULL,
    seq BIGINT NOT NULL,
    metric VARCHAR(64) NOT NULL,
    value_number DOUBLE PRECISION NOT NULL,
    measured_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    received_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ts_source VARCHAR(16) NOT NULL CHECK (ts_source IN ('device', 'server')),
    CONSTRAINT uq_telemetry UNIQUE (device_id, metric, measured_at)
);
SELECT create_hypertable('telemetry', by_range('measured_at'), if_not_exists => TRUE);
CREATE INDEX IF NOT EXISTS idx_telemetry_query
    ON telemetry (device_id, metric, measured_at DESC);

CREATE TABLE IF NOT EXISTS device_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(64) NOT NULL REFERENCES devices(device_id),
    event_id VARCHAR(160) NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    boot_id VARCHAR(64) NOT NULL,
    seq BIGINT NOT NULL,
    event_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    received_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    payload_json JSONB NOT NULL,
    CONSTRAINT uq_device_event UNIQUE (device_id, event_id)
);
CREATE INDEX IF NOT EXISTS idx_events_time ON device_events(device_id, event_at DESC);

CREATE TABLE IF NOT EXISTS device_status (
    device_id VARCHAR(64) PRIMARY KEY REFERENCES devices(device_id),
    current_state VARCHAR(8) NOT NULL CHECK (current_state IN ('online', 'offline')),
    received_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    boot_id VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS device_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(64) NOT NULL REFERENCES devices(device_id),
    state VARCHAR(8) NOT NULL CHECK (state IN ('online', 'offline')),
    received_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    boot_id VARCHAR(64) NOT NULL
);
