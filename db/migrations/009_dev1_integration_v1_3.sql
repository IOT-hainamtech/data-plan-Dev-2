CREATE TABLE IF NOT EXISTS status_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_event_id UUID NOT NULL UNIQUE,
    device_id VARCHAR(64) NOT NULL REFERENCES devices(device_id),
    payload_json JSONB NOT NULL,
    delivery_state VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (delivery_state IN ('PENDING','IN_FLIGHT','DELIVERED','FAILED')),
    attempt_count INTEGER NOT NULL DEFAULT 0,
    failure_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    locked_by VARCHAR(128), locked_until TIMESTAMP WITHOUT TIME ZONE,
    last_error VARCHAR(500), last_http_status INTEGER,
    ack_id VARCHAR(160), acked_at TIMESTAMP WITHOUT TIME ZONE,
    delivered_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_status_outbox_claim ON status_outbox(next_attempt_at,id)
    WHERE delivery_state IN ('PENDING','IN_FLIGHT');

CREATE TABLE IF NOT EXISTS alarm_lifecycle (
    wire_alarm_key VARCHAR(256) PRIMARY KEY,
    org_code VARCHAR(64) NOT NULL REFERENCES organizations(org_code),
    state VARCHAR(20) NOT NULL DEFAULT 'open'
        CHECK (state IN ('open','acknowledged','in_progress','closed')),
    state_rank SMALLINT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    payload_hash VARCHAR(64), actor_ref VARCHAR(160), note TEXT,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
