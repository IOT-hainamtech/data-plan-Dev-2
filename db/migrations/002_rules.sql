-- Stage 2 Rule Engine demo: not yet the complete URD Rule/Alarm contract.
CREATE TABLE IF NOT EXISTS rule_definitions (
    rule_code VARCHAR(64) PRIMARY KEY,
    device_id VARCHAR(64) NOT NULL REFERENCES devices(device_id),
    rule_kind VARCHAR(20) NOT NULL CHECK (rule_kind IN ('THRESHOLD', 'STATE_CHANGE')),
    metric VARCHAR(64),
    event_type VARCHAR(80),
    threshold_value DOUBLE PRECISION,
    hysteresis_value DOUBLE PRECISION NOT NULL DEFAULT 0,
    hold_seconds INTEGER NOT NULL DEFAULT 0 CHECK (hold_seconds >= 0),
    quiet_seconds INTEGER NOT NULL DEFAULT 0 CHECK (quiet_seconds >= 0),
    severity VARCHAR(16) NOT NULL DEFAULT 'HIGH' CHECK (severity IN ('INFO','WARNING','HIGH','CRITICAL')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS idx_rule_lookup ON rule_definitions(device_id, rule_kind, enabled);

CREATE TABLE IF NOT EXISTS rule_runtime_state (
    rule_code VARCHAR(64) NOT NULL REFERENCES rule_definitions(rule_code),
    device_id VARCHAR(64) NOT NULL REFERENCES devices(device_id),
    hold_started_at TIMESTAMP WITHOUT TIME ZONE,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    last_sample_at TIMESTAMP WITHOUT TIME ZONE,
    last_fired_at TIMESTAMP WITHOUT TIME ZONE,
    PRIMARY KEY (rule_code, device_id)
);

CREATE TABLE IF NOT EXISTS alarm_occurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_key VARCHAR(160) NOT NULL UNIQUE,
    rule_code VARCHAR(64) NOT NULL REFERENCES rule_definitions(rule_code),
    device_id VARCHAR(64) NOT NULL REFERENCES devices(device_id),
    severity VARCHAR(16) NOT NULL CHECK (severity IN ('INFO','WARNING','HIGH','CRITICAL')),
    event_type VARCHAR(80) NOT NULL,
    triggered_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    payload_json JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_alarm_device_time ON alarm_occurrences(device_id, triggered_at DESC);

CREATE TABLE IF NOT EXISTS alarm_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_key VARCHAR(160) NOT NULL UNIQUE REFERENCES alarm_occurrences(alarm_key),
    payload_json JSONB NOT NULL,
    delivery_state VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (delivery_state IN ('PENDING','DELIVERED')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    last_error VARCHAR(500),
    delivered_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_outbox_pending ON alarm_outbox(delivery_state, next_attempt_at);

