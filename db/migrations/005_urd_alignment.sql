-- Additive URD alignment: retain valid and error telemetry reports idempotently.
CREATE TABLE IF NOT EXISTS telemetry_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(64) NOT NULL REFERENCES devices(device_id),
    boot_id VARCHAR(64) NOT NULL,
    seq BIGINT NOT NULL CHECK (seq >= 0),
    quality VARCHAR(8) NOT NULL CONSTRAINT ck_telemetry_reports_quality
        CHECK (quality IN ('good', 'error')),
    measured_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    received_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    payload_json JSONB NOT NULL,
    CONSTRAINT uq_telemetry_report UNIQUE (device_id, boot_id, seq)
);
CREATE INDEX IF NOT EXISTS idx_telemetry_reports_time
    ON telemetry_reports (device_id, measured_at DESC);
